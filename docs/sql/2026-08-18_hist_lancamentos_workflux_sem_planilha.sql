left join rdo_r rr on upper(trim(n.name))=rr.nm
left join rdo_e re on upper(trim(n.name))=re.nm
left join eq_o eo on upper(trim(n.name))=eo.nm
left join eq_s es on upper(trim(n.name))=es.nm
order by total_refs desc, n.name;
