rdo_r as (select upper(trim(responsavel)) as nm, count(*) as c, min(data) as dmin, max(data) as dmax from rdo_diarios where company_id='a1b2c3d4-e5f6-7890-abcd-ef1234567890' and responsavel is not null and trim(responsavel)<>'' group by 1),
